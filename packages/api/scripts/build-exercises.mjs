/**
 * Regenerates `src/exercises-data.ts` from the upstream dataset.
 *
 * Run by hand and commit the result:
 *
 *   node packages/api/scripts/build-exercises.mjs
 *
 * Deliberately not a build step. The catalogue changes about never, and a build
 * that reaches the network is a build that fails on a plane.
 *
 * Instructions are dropped. They are eleven languages of prose per exercise,
 * seventeen megabytes in total, for a screen that shows an animation, and the
 * animation is the part people look at.
 */
import { writeFile } from "node:fs/promises";

/**
 * Pinned rather than `main`: the media is served straight to users from this
 * same commit, and a dataset that reorganised itself upstream would break every
 * image at once with nothing in this repository having changed.
 */
const SHA = "7455efae41b330c265e7cd4b78dfa848e7ce5ebd";
const SOURCE = `https://raw.githubusercontent.com/hasaneyldrm/exercises-dataset/${SHA}/data/exercises.json`;

/** Below this, the upstream shape changed and the output is not worth writing. */
const MINIMUM_ROWS = 1000;

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: ${response.status}`);
const raw = await response.json();

/** `images/0001-2gPfomN.jpg` -> `0001-2gPfomN`, shared with the animation. */
const stem = (path) =>
	String(path ?? "")
		.replace(/^.*\//, "")
		.replace(/\.[a-z0-9]+$/i, "");

const rows = raw
	.map((entry) => ({
		id: String(entry.id ?? ""),
		name: String(entry.name ?? ""),
		bodyPart: String(entry.body_part ?? ""),
		equipment: String(entry.equipment ?? ""),
		target: String(entry.target ?? ""),
		secondary: Array.isArray(entry.secondary_muscles)
			? entry.secondary_muscles
			: [],
		media: stem(entry.image),
	}))
	// The image and the animation have to share a stem, or one field cannot
	// address both and `exerciseGif` starts pointing at nothing.
	.filter((row, index) => {
		const source = raw[index];
		return (
			row.id &&
			row.name &&
			row.bodyPart &&
			row.media &&
			row.media === stem(source.gif_url)
		);
	})
	.sort((a, b) => a.name.localeCompare(b.name));

if (rows.length < MINIMUM_ROWS) {
	throw new Error(`only ${rows.length} usable rows, upstream changed shape`);
}

const header = `// Generated by scripts/build-exercises.mjs. Do not edit.
//
// Source: hasaneyldrm/exercises-dataset at ${SHA}.
// Exercise imagery is © Gym visual (https://gymvisual.com/) and is served from
// the same commit rather than copied into this repository.

import type { Exercise } from "./exercises";

export const ROWS: Exercise[] = `;

await writeFile(
	new URL("../src/exercises-data.ts", import.meta.url),
	`${header}${JSON.stringify(rows, null, "\t")};\n`,
);

console.log(`${rows.length} exercises written`);
